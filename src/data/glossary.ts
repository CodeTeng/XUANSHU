/** 查询：先查术语，再查十神，再查长生 */
export function lookupTerm(key: string): TermEntry | null {
  if (TERMS[key]) return TERMS[key]
  if (SHISHEN[key]) {
    const s = SHISHEN[key]
    return { plain: `${s.word}。${s.plain}`, source: `与日主的关系：${s.rel}`, level: '⚖' }
  }
  if (CHANGSHENG[key]) {
    const c = CHANGSHENG[key]
    return { plain: c.plain, source: `《三命通会》卷二：「${c.origin}」`, level: '✅' }
  }
  return null
}
