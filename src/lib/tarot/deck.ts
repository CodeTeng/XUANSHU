function buildMinor(suit: Suit, seeds: MinorSeed[]): TarotCard[] {
  return seeds.map((s, i) => {
    const rank = i + 1
    const meta = SUIT_META[suit]
    return {
      id: `minor-${suit}-${rank}`,
      no: RANK_NUM[rank],
      name: `${meta.name}${RANK_NAME[rank]}`,
      en: `${RANK_EN[rank]} of ${meta.en}`,
      arcana: 'minor' as Arcana,
      suit,
      rank,
      glyph: `suit-${suit}-${rank}`,
      element: meta.element,
      up: s.up,
      rev: s.rev,
      upText: s.upText,
      revText: s.revText,
    }
  })
}

